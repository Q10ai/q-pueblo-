import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
const root='public/';
const read = path => readFileSync(root+path,'utf8');
const manifest=JSON.parse(read('release-manifest.json'));
assert.equal(manifest.schema,'qp-public-release-manifest-v1');
assert.equal(manifest.releaseId,'QP-PUBLIC-2026-11-13-EXPERIENCE-RC1');
assert.equal(manifest.publicationAuthority,'human_required');
for(const value of ['automatedAIAnswers','authenticatedEvidenceIntake','autonomousPublication','realTimeMeetingIngestion'])assert.equal(manifest.capabilityClaims[value],false);
for(const path of ['release-check.html','release-check.js','assets/q-pueblo-header-wide.png','assets/q-pueblo-approved-logo.jpg','index.html','issues.html','reports.html','qify.html','q-tools.html','entities.html','workbench.html','method.html','es.html','api/v1/capabilities.json'])assert(existsSync(root+path),'Required public file missing: '+path);
assert(read('release-check.html').includes('release-check.js'));
assert(read('release-check.html').includes('QP-PUBLIC-2026-11-13-EXPERIENCE-RC1'));
assert(!/<script(?![^>]*src=)/i.test(read('release-check.html')),'No inline JS in verification page');
assert(read('release-check.js').includes("cache:'no-store'"),'Release check must bypass stale caches');
assert(!/localStorage|sessionStorage|sendBeacon|XMLHttpRequest/.test(read('release-check.js')));
assert(read('index.html').includes('href="release-check.html"'));
assert(read('method.html').includes('href="release-check.html"'));
const cap=JSON.parse(read('api/v1/capabilities.json'));
assert.equal(cap.server_side_contribution_intake,false);
assert.equal(cap.autonomous_public_research_agents,false);
console.log('PASS public release-manifest/checker, human deployment gate, links, conservative backend configuration and script policy');
