import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {buildCandidateRegistry,ensureControlled,appendCandidateRevision,financialStageTotals,requireAggregateElectionRows,digest} from '../lib/qp-evidence-ledger.mjs';
const rawIssue=readFileSync('public/data/q-pueblo-issue-index-2026-11-09.json','utf8');
const rawReport=readFileSync('public/data/q-pueblo-qified-reports-v2-2026-11-09.json','utf8');
const issues=JSON.parse(rawIssue).issues,reports=JSON.parse(rawReport).reports;
const input={issues,reports,issueDigest:digest(rawIssue),reportDigest:digest(rawReport)};
const registry=buildCandidateRegistry(input);
assert.equal(ensureControlled(registry),true);
assert.equal(registry.counts.historical_issues,174);
assert.equal(registry.counts.originally_source_mapped,82);
assert.equal(registry.counts.originally_unmapped,92);
assert.equal(registry.counts.current_reports,14);
assert.equal(registry.counts.explicit_report_lead_issues,11);
assert.equal(registry.counts.remaining_unmapped_without_explicit_report_lead,81);
assert.equal(JSON.stringify(registry),JSON.stringify(buildCandidateRegistry(input)),'Deterministic rebuild');
assert.equal(registry.historical_issues.filter(x=>x.coverage_state==='UNMAPPED_WITH_EXPLICIT_REPORT_LEAD').length,11);
assert.ok(registry.historical_issues.every(x=>!x.independent_verification));
assert.ok(registry.candidate_links.every(x=>x.public_finding===false));
assert.ok(registry.candidate_links.every(x=>x.source_ref_ids.every(s=>registry.source_url_refs.some(r=>r.id===s))));
assert.ok(registry.source_url_refs.every(x=>x.url.startsWith('https://')));
const altered=structuredClone(registry);
altered.boundary.automatic_publication=true;
assert.throws(()=>ensureControlled(altered),/Auto publication/);
assert.throws(()=>buildCandidateRegistry({...input,issues:[issues[0],issues[0]]}),/duplicate identifier/);
assert.throws(()=>buildCandidateRegistry({...input,reports:[{id:'A-1',issueIds:['NOT-AN-ISSUE'],sources:[]}]}),/missing historical issue/);
const prior={revisions:[{revision_id:'REV-old',review_note:'older',source_id:'S-old',reviewed_at:'2026-11-10'}],publication_state:'NOT_APPROVED'};
const proposed={review_note:'Revise after records review',source_id:'S-new',reviewed_at:'2026-11-12'};
const revised=appendCandidateRevision(prior,proposed);
assert.equal(prior.revisions.length,1);
assert.equal(revised.revisions.length,2);
assert.equal(appendCandidateRevision(revised,proposed).revisions.length,2);
assert.equal(revised.publication_state,'NOT_APPROVED');
assert.throws(()=>appendCandidateRevision(prior,{review_note:'missing'}),/Provenance/);
const scope={agency:'Pueblo City',jurisdiction:'Pueblo CO',fiscalYear:'2026',currency:'USD'};
const row=(transaction_id,stage,amount_cents,overrides={})=>({...scope,source_id:'S1',transaction_id,stage,amount_cents,...overrides});
const totals=financialStageTotals([row('A','appropriated',10000),row('B','paid',3500)],scope);
assert.equal(totals.totals_by_stage_in_minor_units.appropriated.amount,10000);
assert.equal(totals.totals_by_stage_in_minor_units.paid.amount,3500);
assert.equal(totals.all_stage_total_is_not_meaningful,true);
assert.throws(()=>financialStageTotals([row('A','paid',3500),row('A','paid',3500)],scope),/Duplicate/);
assert.throws(()=>financialStageTotals([row('A','paid',3500,{agency:'Another'})],scope),/Cross-scope/);
assert.throws(()=>financialStageTotals([row('A','paid',1.5)],scope),/integer/);
const aggregate={geography_id:'precinct-A',source_id:'S1',observed_at:'2026-11-03',boundary_version:'2026',count:125};
assert.equal(requireAggregateElectionRows([aggregate]).length,1);
assert.throws(()=>requireAggregateElectionRows([{...aggregate,street_address:'123 Any St'}]),/Individual-level/);
assert.throws(()=>requireAggregateElectionRows([{...aggregate,count:9}]),/small cells/);
assert.throws(()=>requireAggregateElectionRows([aggregate],{minimumCell:5}),/Minimum cell/);
console.log(JSON.stringify({result:'PASS',issue_records:registry.counts.historical_issues,candidate_issue_leads:registry.counts.explicit_report_lead_issues,unmapped_without_explicit_leads:registry.counts.remaining_unmapped_without_explicit_report_lead,source_url_refs:registry.counts.distinct_report_source_urls,privacy:'aggregate guard tested; not a complete re-identification audit',publication:'OFF'},null,2));
