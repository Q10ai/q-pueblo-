import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const read=path=>readFileSync(path,'utf8');
const snapshot=read('public/evidence-data.js');
const ctx={window:{},module:{exports:{}}};
vm.runInNewContext(snapshot,ctx,{timeout:3000});
const data=ctx.module.exports;
assert.equal(data.schema,'qp-resident-evidence-v1');
assert.equal(data.budget.total,128202143);
assert.equal(data.budget.adopted,'2025-11-24');
assert.equal(data.budget.groups.length,7);
assert.equal(data.budget.groups.reduce((s,x)=>s+x.amount,0),data.budget.total,'Ordinance category sums must reconcile');
assert.equal(new Set(data.budget.groups.map(x=>x.id)).size,7,'Duplicate budget IDs');
assert.equal(data.budget.source,'https://www.pueblo.us/DocumentCenter/View/39357/Ordinance11075-Adopted-Budget');
assert.equal(data.county.updated,'2026-08-08');
assert.equal(data.county.initiatives.length,26);
assert.equal(new Set(data.county.initiatives.map(x=>x[0])).size,26);
assert.equal(data.county.initiatives.filter(x=>x[2]==='Underway').length,22);
assert.equal(data.county.initiatives.filter(x=>x[2]==='Waiting').length,3);
assert.equal(data.county.initiatives.filter(x=>x[2]==='Complete').length,1);
assert.equal(data.reviewDocket.length,1);
assert(data.reviewDocket[0].summary.includes('FY2024'),'Keep City ordinance year conflict in review docket');
const code=read('public/evidence-desk.js');
const test={window:{},module:{exports:{}}};
vm.runInNewContext(code,test,{timeout:3000});
const core=test.module.exports;
assert(core.budgetValid(data.budget),'Budget must reconcile to adopted total');
const c=core.comparison(data.budget,'police','fire');
assert.equal(c.delta,13772295);
assert.equal(c.spread,13772295);
assert(Math.abs(c.shareA-34.051)<.01);
assert.equal(core.countyStats(data.county.initiatives).total,26);
assert.throws(()=>core.comparison({...data.budget,total:1},'police','fire'));
assert.throws(()=>core.comparison(data.budget,'invalid','fire'));
assert(!/XMLHttpRequest|sendBeacon|localStorage|sessionStorage/.test(code),'No user-input persistence or telemetry');
assert(code.includes("fetch('data/q-pueblo-qified-reports-v2-2026-11-09.json'"),'Desk reads the current 14-report ledger');
assert(code.includes('reportLoad')&&code.includes('budgetDisplay')&&code.includes('countyDisplay')&&code.includes('receipt()'));
const reports=JSON.parse(read('public/data/q-pueblo-qified-reports-v2-2026-11-09.json'));
assert.equal(reports.reports.length,14);
assert(reports.reports.every(x=>x.slug&&x.sourceChecked&&x.reviewDue&&Array.isArray(x.sources)&&x.sources.length>0));
const page=read('public/evidence-desk.html'),css=read('public/evidence-desk.css'),home=read('public/index.html');
for(const id of ['budget-rows','budget-total','desk-a','desk-b','desk-compare-result','county-list','county-status','county-portfolio','desk-reports','desk-search','desk-download','desk-docket'])
  assert(page.includes('id="'+id+'"'),'Missing evidence desk widget '+id);
assert(page.indexOf('src="evidence-data.js"')<page.indexOf('src="evidence-desk.js"'));
assert(home.includes('href="evidence-desk.html"'),'Desk must be discoverable on homepage');
assert(home.includes('id="home-q"') && !home.includes('name="q"'),'Private home question must not become query parameter');
assert(css.includes('@media(max-width:640px)'));
const method=read('public/method.html');
assert(method.includes('Ownership, funding and accountability — open disclosures'),'No unsupported operator identity or funded editorial claim');
assert(method.includes('A staffed public submission queue')&&method.includes('not in operation'),'Non-operational corrections workflow must be disclosed');
assert(method.includes('evidence-desk.html#challenge'),'Known documentary contradiction must remain navigable');
console.log('PASS evidence desk: 7 reconciled budget groups, actual math, 26 county priorities, 14 dated reports, correction docket, source boundaries, privacy and mobile UI.');
