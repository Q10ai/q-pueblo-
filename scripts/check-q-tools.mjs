import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync,existsSync} from 'node:fs';
const html=readFileSync('public/q-tools.html','utf8');
const css=readFileSync('public/q-tools.css','utf8');
const js=readFileSync('public/q-tools.js','utf8');
const w={};vm.runInNewContext(js,{window:w}, {timeout:3000});
const {ee,t2y,lifecycle}=w.QP_TOOLS_CORE;
const base={name:'safe source-first',compute:1,energy:1,latency:2,error:1,review:2,rework:1,trust:1,public:1,yield:.8,safe:true,evidence:true,authority:true};
const variant={...base,name:'unknown',compute:0,safe:false};
assert.equal(ee(base,variant).leastCost,'safe source-first');
assert.equal(ee({...base,safe:false},variant).disposition,'HOLD_NO_ELIGIBLE_ROUTE');
assert.equal(ee(base,{...base,name:'second'}).tie,true);
const qualified=t2y({truth:.95,yield:.8,agency:1,reversibility:1,harm:0,provenance:true,approval:true,rollback:true});
assert.equal(qualified.disposition,'CANDIDATE_FOR_HUMAN_REVIEW');
assert.equal(t2y({...qualified,truth:.1,yield:1,harm:0,provenance:true,approval:true,rollback:true}).disposition,'HOLD_EVIDENCE_OR_REVIEW');
assert.equal(t2y({truth:1,yield:1,agency:1,reversibility:1,harm:0,provenance:false,approval:true,rollback:true}).reviewReady,false);
const costs=lifecycle({name:'A',upfront:100,annual:10,reserve:20},{name:'B',upfront:150,annual:5,reserve:20},5);
assert.equal(costs.options[0].total,170);
assert.equal(costs.options[1].total,195);
assert.equal(costs.lowerCost,'A');
assert.throws(()=>lifecycle({name:'A',upfront:-1,annual:0,reserve:0},{name:'B',upfront:0,annual:0,reserve:0},1));
for(const name of ['q-tools.html','q-tools.css','q-tools.js'])assert(existsSync('public/'+name),'Missing '+name);
for(const id of ['run-ee','run-t2y','run-lifecycle','run-challenge','qt-md','qt-json','qt-report','qt-copy','qt-print'])assert(html.includes('id="'+id+'"'),'Missing control '+id);
assert(html.includes('src="q-tools.js"')&&html.includes('href="q-tools.css"'));
assert(css.includes('@media')&&css.includes('object-fit:contain'));
assert(!/\bfetch\(|XMLHttpRequest|localStorage|sessionStorage|sendBeacon/.test(js),'Must not transmit or persist form data');
assert(!/<script(?![^>]*src=)/i.test(html),'Inline scripts violate CSP');
for(const p of ['public/index.html','public/workbench.html','public/launch.html']) assert(readFileSync(p,'utf8').includes('href="q-tools.html"'),p+' missing Q Tools link');
console.log('PASS Q Tools math, holds, lifecycle, local-only privacy, navigation, controls, and CSP boundary.');